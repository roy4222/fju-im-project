import { chromium } from "playwright";
const [,, role, path, out, w = "1440", full = "1"] = process.argv;
const b = await chromium.launch({ executablePath: process.env.CHROME_PATH });
const ctx = await b.newContext({ viewport: { width: Number(w), height: 900 }, deviceScaleFactor: Number(w) < 500 ? 2 : 1 });
const p = await ctx.newPage();
p.on("pageerror", (e) => console.log("pageerror", e.message));
const B = "http://127.0.0.1:3217";
await p.goto(`${B}/api/proto-role?role=${role}&returnTo=${encodeURIComponent(path)}`, { waitUntil: "networkidle" });
await p.waitForTimeout(500);
await p.screenshot({ path: out, fullPage: full === "1" });
await b.close();
